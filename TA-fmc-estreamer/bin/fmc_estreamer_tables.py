"""
fmc_estreamer_tables.py - fixed value-to-name tables for connection events.

Plain data, no code. The FMC sends most names as metadata records with the
events (rules, zones, interfaces, devices, applications, ...); these tables
cover values the FMC does not name in its stream:

  * IP protocol numbers: names as in the IANA "Assigned Internet Protocol
    Numbers" registry (0 is written as Unknown).
  * TLS cipher suites: names as in the IANA "TLS Cipher Suites" registry
    (the TLS 1.3 suites are named by the FMC's own SSL cipher metadata).
  * Rule reasons, SSL actions, flow statuses, certificate statuses, flow flags
    and flow messages: the code tables in Cisco's public Secure Firewall
    eStreamer Integration Guide.

The names and their coverage are kept exactly as earlier versions of this
add-on wrote them, so searches and dashboards keep working.
"""

